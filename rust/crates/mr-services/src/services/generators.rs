/// Renders dnsmasq DHCP and DNS server configuration.
pub fn generate_dnsmasq(cfg: &SystemConfig) -> Result<String> {
    let mut runtime = cfg.clone();
    runtime.lan.interface = cfg.runtime_lan_interface().to_string();
    let cfg = &runtime;

    let mut buf = String::with_capacity(2048);
    buf.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    buf.push_str("# File: /etc/dnsmasq.d/minimalrouter.conf\n\n");
    let _ = writeln!(buf, "domain={}", cfg.system.domain);
    let _ = writeln!(buf, "interface={}", cfg.lan.interface);
    let mut listen = vec!["127.0.0.1".to_string(), cfg.lan.ip_address.clone()];
    // The firewall exposes DNS to authenticated wg0 peers; bind dnsmasq to the
    // tunnel so policy and availability agree. ExtraLAN hosts no DNS service.
    if cfg.wireguard.enabled && !cfg.wireguard.interface.is_empty() && !cfg.wireguard.address.is_empty() {
        let wg_ip = cfg.wireguard.address.split('/').next().unwrap_or("");
        if !wg_ip.is_empty() {
            let _ = writeln!(buf, "interface={}", cfg.wireguard.interface);
            listen.push(wg_ip.to_string());
        }
    }
    let _ = writeln!(buf, "listen-address={}", listen.join(","));
    // bind-dynamic tolerates wg0 appearing after dnsmasq starts.
    buf.push_str("bind-dynamic\nno-resolv\nstrict-order\ncache-size=1000\nbogus-priv\ndomain-needed\n");
    buf.push_str("# DNS rebind attack protection\nstop-dns-rebind\nrebind-domain-ok=/use-application-dns.net/\n\n");

    if !cfg.dhcp.dns_servers.is_empty() {
        buf.push_str("# Upstream DNS servers\n");
        for dns in cfg.dhcp.dns_servers.iter() {
            let _ = writeln!(buf, "server={}", dns);
        }
        buf.push('\n');
    }
    if cfg.dhcp.dns_enabled {
        buf.push_str(&generate_doh_dnsmasq_integration(cfg));
    }

    if cfg.dhcp.enabled {
        buf.push_str("# DHCP pool\n");
        // Leases persist in a dnsmasq-owned directory, separate from routerd's store.
        buf.push_str("dhcp-leasefile=/var/lib/minimalrouter-dhcp/dnsmasq.leases\n");
        let _ = writeln!(buf, "dhcp-range={},{},{},{}", cfg.dhcp.range_start, cfg.dhcp.range_end, cfg.lan.netmask, cfg.dhcp.lease_time);
        let _ = writeln!(buf, "dhcp-option=option:router,{}", cfg.lan.ip_address);
        let _ = writeln!(buf, "dhcp-option=option:dns-server,{}\n", cfg.lan.ip_address);
        if !cfg.dhcp.static_leases.is_empty() {
            buf.push_str("# Static DHCP leases\n");
            for lease in cfg.dhcp.static_leases.iter() {
                let hostname = lease.hostname.trim();
                if hostname.is_empty() {
                    let _ = writeln!(buf, "dhcp-host={},{}", lease.mac, lease.ip_address);
                } else {
                    let _ = writeln!(buf, "dhcp-host={},{},{}", lease.mac, lease.ip_address, hostname);
                }
            }
        }
    } else {
        buf.push_str("# DHCP disabled\n");
    }

    if !cfg.dns.records.is_empty() {
        buf.push_str("\n# Static DNS records\n");
        for rec in cfg.dns.records.iter() {
            let _ = writeln!(buf, "host-record={},{}", rec.name, rec.ip);
        }
    }

    if cfg.adguard.enabled {
        buf.push_str("\n# DNS Filter global sinkhole blocklist\n");
        buf.push_str("conf-file=/etc/dnsmasq.d/adblock_hosts.conf\n");
    }
    write_dns_filter_nftsets(&mut buf, cfg);
    Ok(buf)
}

fn quote_pppd(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Rendered peer config and secret material.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct PPPoEConfigBundle {
    pub peer_config: String,
    pub chap_secrets: String,
    pub pap_secrets: String,
}

/// Renders pppd configuration files.
pub fn generate_pppoe(cfg: &SystemConfig) -> Result<PPPoEConfigBundle> {
    let mut peer = String::new();
    peer.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    let _ = writeln!(peer, "plugin pppoe.so {}", cfg.wan.interface);
    let _ = writeln!(peer, "name \"{}\"", quote_pppd(&cfg.wan.username));
    peer.push_str("noipdefault\nnoauth\nnoipv6\ndefaultroute\nreplacedefaultroute\n");
    peer.push_str("persist\nmaxfail 0\nholdoff 5\n");
    // LCP echo detects a dead peer instead of leaving a zombie session up.
    peer.push_str("lcp-echo-interval 5\nlcp-echo-failure 4\n");
    if cfg.wan.mtu > 0 {
        let _ = writeln!(peer, "mtu {}", cfg.wan.mtu);
        let _ = writeln!(peer, "mru {}", cfg.wan.mtu);
    }
    let secret =
        format!("# Generated by Minimal Router OS — do not edit manually\n\"{}\" * \"{}\" *\n", quote_pppd(&cfg.wan.username), quote_pppd(&cfg.wan.password));
    // Some carrier CPEs negotiate PAP instead of CHAP; the secret is identical.
    Ok(PPPoEConfigBundle { peer_config: peer, chap_secrets: secret.clone(), pap_secrets: secret })
}

/// Renders the WPA2/WPA3 hostapd configuration.
pub fn generate_hostapd(cfg: &SystemConfig) -> Result<String> {
    let mut buf = String::new();
    buf.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    buf.push_str("# File: /etc/hostapd/hostapd.conf\n\n");
    if !cfg.wifi.enabled {
        buf.push_str("# Wi-Fi Access Point is disabled\n");
        return Ok(buf);
    }
    let iface = if cfg.wifi.interface.is_empty() { "wlan0" } else { &cfg.wifi.interface };
    let _ = writeln!(buf, "interface={}", iface);
    let _ = writeln!(buf, "bridge={}", WIFI_BRIDGE_INTERFACE);
    buf.push_str("driver=nl80211\n");
    let _ = writeln!(buf, "ssid={}", cfg.wifi.ssid);
    if cfg.wifi.band == "5ghz" {
        buf.push_str("hw_mode=a\nieee80211n=1\nieee80211ac=1\n");
    } else {
        buf.push_str("hw_mode=g\nieee80211n=1\n");
    }
    let channel = if cfg.wifi.channel <= 0 { 36 } else { cfg.wifi.channel };
    let _ = writeln!(buf, "channel={}", channel);
    buf.push_str(if cfg.wifi.hide_ssid { "ignore_broadcast_ssid=1\n" } else { "ignore_broadcast_ssid=0\n" });
    // WPA2/WPA3 transition mode with protected management frames; no TKIP.
    buf.push_str("wpa=2\n");
    let _ = writeln!(buf, "wpa_passphrase={}", cfg.wifi.passphrase);
    buf.push_str("wpa_key_mgmt=WPA-PSK SAE\nieee80211w=1\nrsn_pairwise=CCMP\n");
    Ok(buf)
}

/// The dummy interface that carries download (ingress) shaping.
pub const QOS_INTERFACE_NAME: &str = "ifb0";

fn qos_interface(cfg: &SystemConfig) -> String {
    let mut iface = cfg.wan.interface.clone();
    if cfg.wan.enabled {
        iface = "ppp0".into();
    }
    if iface.is_empty() {
        iface = "eth0".into();
    }
    iface
}

/// argv-only tc operations for CAKE or fq_codel; no text reaches a shell.
pub fn qos_commands(cfg: &SystemConfig) -> Result<Vec<Vec<String>>> {
    if !cfg.qos.enabled {
        return Ok(Vec::new());
    }
    let iface = qos_interface(cfg);
    let down = format!("{}kbit", cfg.qos.download_limit_mbps.wrapping_mul(1000));
    let up = format!("{}kbit", cfg.qos.upload_limit_mbps.wrapping_mul(1000));
    let ifb = QOS_INTERFACE_NAME;
    let argv = |parts: &[&str]| parts.iter().map(|s| s.to_string()).collect::<Vec<_>>();
    let mirred = argv(&[
        "filter", "add", "dev", &iface, "parent", "ffff:", "protocol", "ip", "u32", "match", "u32", "0", "0", "action", "mirred", "egress", "redirect", "dev",
        ifb,
    ]);
    match cfg.qos.algorithm.as_str() {
        "fq_codel" => Ok(vec![
            argv(&["qdisc", "add", "dev", &iface, "root", "handle", "1:", "htb", "default", "10"]),
            argv(&["class", "add", "dev", &iface, "parent", "1:", "classid", "1:10", "htb", "rate", &up, "ceil", &up, "burst", "64k"]),
            argv(&["qdisc", "add", "dev", &iface, "parent", "1:10", "handle", "10:", "fq_codel", "target", "5ms", "interval", "100ms", "limit", "10240"]),
            argv(&["qdisc", "add", "dev", &iface, "handle", "ffff:", "ingress"]),
            mirred,
            argv(&["qdisc", "add", "dev", ifb, "root", "handle", "1:", "htb", "default", "10"]),
            argv(&["class", "add", "dev", ifb, "parent", "1:", "classid", "1:10", "htb", "rate", &down, "ceil", &down, "burst", "64k"]),
            argv(&["qdisc", "add", "dev", ifb, "parent", "1:10", "handle", "10:", "fq_codel", "target", "5ms", "interval", "100ms", "limit", "10240"]),
        ]),
        "cake" => Ok(vec![
            argv(&["qdisc", "add", "dev", &iface, "root", "cake", "bandwidth", &up, "besteffort", "nat", "wash", "no-split-gso"]),
            argv(&["qdisc", "add", "dev", &iface, "handle", "ffff:", "ingress"]),
            mirred,
            argv(&["qdisc", "add", "dev", ifb, "root", "cake", "bandwidth", &down, "besteffort", "nat", "wash", "no-split-gso"]),
        ]),
        other => Err(errorf!("unsupported QoS algorithm: {}", other)),
    }
}

/// A human-readable, non-executable record of the exact tc operations.
pub fn generate_qos(cfg: &SystemConfig) -> Result<String> {
    if !cfg.qos.enabled {
        return Ok("# QoS disabled\n".into());
    }
    let mut buf = String::new();
    buf.push_str("# Generated by Minimal Router OS — non-executable QoS plan\n");
    buf.push_str("# router-applyd invokes /sbin/tc directly with these argv values\n\n");
    for args in qos_commands(cfg)? {
        let _ = writeln!(buf, "/sbin/tc {}", args.join(" "));
    }
    Ok(buf)
}

/// A non-caching, authenticated, Internet-only forward proxy configuration.
pub fn generate_squid_config(cfg: &SystemConfig) -> Result<String> {
    let mut buf = String::new();
    buf.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    let _ = writeln!(buf, "http_port {}:{}\n", cfg.lan.ip_address, cfg.squid_proxy.port);
    buf.push_str("# Disable disk & memory caching (Pure forward proxy)\ncache deny all\ncache_mem 0 MB\n");
    buf.push_str("# Short graceful shutdown so config rollback never waits on idle clients\nshutdown_lifetime 2 seconds\n\n");
    if cfg.squid_proxy.enabled {
        buf.push_str("# Basic authentication scheme (NCSA htpasswd)\n");
        buf.push_str("auth_param basic program /usr/lib/squid/basic_ncsa_auth /etc/squid/passwd\n");
        buf.push_str("auth_param basic realm Minimal Router OS Proxy\n");
        buf.push_str("auth_param basic credentialsttl 2 hours\n");
        let lan_network = net::parse_cidr(&cfg.lan.cidr).map(|(_, n)| n.to_string()).unwrap_or_else(|| "<nil>".into());
        let _ = writeln!(buf, "acl localnet src {}", lan_network);
        buf.push_str("acl authenticated proxy_auth REQUIRED\n");
        // Defense in depth for segmentation: Squid must reject destinations
        // that are never valid Internet proxy targets.
        let mut blocked: Vec<String> = [
            "0.0.0.0/8",
            "10.0.0.0/8",
            "100.64.0.0/10",
            "127.0.0.0/8",
            "169.254.0.0/16",
            "172.16.0.0/12",
            "192.0.0.0/24",
            "192.0.2.0/24",
            "192.168.0.0/16",
            "198.18.0.0/15",
            "198.51.100.0/24",
            "203.0.113.0/24",
            "224.0.0.0/4",
            "240.0.0.0/4",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect();
        blocked.push(lan_network);
        if cfg.wireguard.enabled {
            if let Some((_, wg)) = net::parse_cidr(&cfg.wireguard.address) {
                blocked.push(wg.to_string());
            }
        }
        for lan in cfg.firewall.extra_lans.iter() {
            if lan.enabled && !lan.cidr.trim().is_empty() {
                if let Some((_, extra)) = net::parse_cidr(&lan.cidr) {
                    blocked.push(extra.to_string());
                }
            }
        }
        for remote in cfg.wg_client.allowed_ips.iter() {
            if let Some((_, remote)) = net::parse_cidr(remote.trim()) {
                if remote.ip.to4().is_some() {
                    blocked.push(remote.to_string());
                }
            }
        }
        let _ = writeln!(buf, "acl blocked_dst dst {}", blocked.join(" "));
        buf.push_str("http_access deny blocked_dst\nhttp_access allow localnet authenticated\n");
    } else {
        buf.push_str("# Proxy disabled\n");
    }
    buf.push_str("http_access deny all\n");
    Ok(buf)
}

fn dynamic_dns_provider(cfg: &SystemConfig) -> String {
    let provider = to_lower(cfg.cloudflare.ddns_provider.trim());
    // Configurations written before provider-aware DDNS were Cloudflare-only.
    if provider.is_empty() { "cloudflare".into() } else { provider }
}

/// Provider-specific configuration for inadyn. No generated shell code runs.
pub fn generate_dynamic_dns(cfg: &SystemConfig) -> Result<String> {
    if !cfg.cloudflare.ddns_enabled {
        return Ok("# Dynamic DNS disabled or not configured\n".into());
    }
    let mut buf = String::new();
    buf.push_str("# Generated by Minimal Router OS — Dynamic DNS\nperiod = 300\n");
    // 30-day forced keep-alive matches No-IP's free-hostname update window.
    buf.push_str("forced-update = 2592000\nallow-ipv6 = false\nsecure-ssl = true\n\n");
    let cf = &cfg.cloudflare;
    match dynamic_dns_provider(cfg).as_str() {
        "noip" => {
            buf.push_str("provider no-ip.com:1 {\n");
            let _ = writeln!(buf, "    username = {}", quote(&cf.ddns_user));
            let _ = writeln!(buf, "    password = {}", quote(&cf.api_token));
            let _ = writeln!(buf, "    hostname = {}", quote(&cf.domain));
            buf.push_str("    checkip-server = api.ipify.org\n    checkip-path = /\n    checkip-ssl = true\n}\n");
        }
        "cloudflare" => {
            buf.push_str("provider cloudflare.com:1 {\n");
            let _ = writeln!(buf, "    username = {}", quote(&cf.zone_name));
            let _ = writeln!(buf, "    password = {}", quote(&cf.api_token));
            let _ = writeln!(buf, "    hostname = {}", quote(&cf.domain));
            buf.push_str("    checkip-server = api.ipify.org\n    checkip-path = /\n    checkip-ssl = true\n    ttl = 300\n    proxied = false\n}\n");
        }
        _ => return Err(errorf!("unsupported dynamic DNS provider {}", quote(&cf.ddns_provider))),
    }
    Ok(buf)
}

pub fn generate_cloudflare_ddns(cfg: &SystemConfig) -> Result<String> {
    generate_dynamic_dns(cfg)
}

/// Only non-secret metadata for a remotely managed Cloudflare Tunnel.
pub fn generate_cloudflare_tunnel(cfg: &SystemConfig) -> Result<String> {
    if !cfg.cloudflare.tunnel_enabled {
        return Ok("# Cloudflare Tunnel disabled\n".into());
    }
    let hostname = cfg.cloudflare.tunnel_hostname.trim();
    if hostname.is_empty() {
        return Err(errorf!("Cloudflare Tunnel hostname is required"));
    }
    Ok(format!(
        "# Generated by Minimal Router OS — remotely managed Cloudflare Tunnel\n# Routing and origin settings are managed in Cloudflare.\n# Expected public hostname: {}\n# Connector token is stored separately and is never written here.\n",
        hostname
    ))
}

