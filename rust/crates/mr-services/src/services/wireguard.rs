/// The human-readable appliance configuration, including Address, which the
/// privileged helper applies with a fixed ip(8) argv.
pub fn generate_wireguard(wg: &WireGuardConfig) -> Result<String> {
    generate(wg, true)
}

/// Only directives accepted by `wg setconf`, so no wg-quick or shell is needed.
pub fn generate_wireguard_runtime(wg: &WireGuardConfig) -> Result<String> {
    generate(wg, false)
}

/// The outbound tunnel (wg1) runtime input.
pub fn generate_wireguard_client_runtime(wg: &WGClientConfig) -> Result<String> {
    // A route-only wg1 with no local address is not a supported topology;
    // enforce it here as well so the privileged helper stays fail-closed.
    match net::parse_cidr(wg.address.trim()) {
        Some((ip, network)) if ip.to4().is_some() => {
            let (ones, bits) = network.mask.size();
            if bits != 32 || ones != 32 {
                return Err(errorf!("WireGuard client address must be an IPv4 /32"));
            }
        }
        _ => return Err(errorf!("WireGuard client address is required and must be a valid IPv4 /32")),
    }
    let mut buf = String::new();
    buf.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    buf.push_str("# Runtime input for wg setconf; interface address is applied separately\n\n");
    buf.push_str("[Interface]\n");
    let _ = writeln!(buf, "PrivateKey = {}", wg.private_key);
    buf.push('\n');
    if wg.allowed_ips.is_empty() {
        return Err(errorf!("WireGuard client must list at least one allowed network"));
    }
    let mut seen = HashSet::new();
    let mut allowed = Vec::with_capacity(wg.allowed_ips.len());
    for entry in wg.allowed_ips.iter() {
        let network = match net::parse_cidr(entry.trim()) {
            Some((_, n)) if n.ip.to4().is_some() => n,
            _ => return Err(errorf!("WireGuard client allowed network {} must be valid IPv4 CIDR", quote(entry))),
        };
        let cidr = network.to_string();
        if !seen.insert(cidr.clone()) {
            return Err(errorf!("WireGuard client duplicates allowed network {}", cidr));
        }
        allowed.push(cidr);
    }
    buf.push_str("# Peer: remote site (outbound tunnel)\n[Peer]\n");
    let _ = writeln!(buf, "PublicKey = {}", wg.public_key);
    if !wg.preshared_key.is_empty() {
        let _ = writeln!(buf, "PresharedKey = {}", wg.preshared_key);
    }
    let _ = writeln!(buf, "AllowedIPs = {}", allowed.join(", "));
    if !wg.endpoint.is_empty() {
        let _ = writeln!(buf, "Endpoint = {}", wg.endpoint);
    }
    // wg(8) treats 0 as "keepalive disabled", so the value is emitted verbatim.
    let _ = writeln!(buf, "PersistentKeepalive = {}", wg.persistent_keepalive);
    Ok(buf)
}

fn generate(wg: &WireGuardConfig, include_address: bool) -> Result<String> {
    let mut buf = String::new();
    let mut seen = HashSet::new();
    buf.push_str("# Generated by Minimal Router OS — do not edit manually\n");
    if include_address {
        buf.push_str("# Runtime file: /run/minimalrouter/wg0.conf\n\n");
    } else {
        buf.push_str("# Runtime input for wg setconf; interface address is applied separately\n\n");
    }
    buf.push_str("[Interface]\n");
    let _ = writeln!(buf, "PrivateKey = {}", wg.private_key);
    if wg.listen_port > 0 {
        let _ = writeln!(buf, "ListenPort = {}", wg.listen_port);
    } else {
        buf.push_str("ListenPort = 51820\n");
    }
    if include_address {
        let _ = writeln!(buf, "Address = {}", wg.address);
    }
    buf.push('\n');
    for peer in wg.peers.iter() {
        if !peer.enabled {
            continue;
        }
        if peer.allowed_ips.len() != 1 {
            return Err(errorf!("WireGuard peer {} must have exactly one IPv4 /32 address", quote(&peer.name)));
        }
        let host_route = match net::parse_cidr(peer.allowed_ips[0].trim()) {
            Some((ip, network)) if ip.to4().is_some() && network.mask.size() == (32, 32) => network.to_string(),
            _ => return Err(errorf!("WireGuard peer {} must use an IPv4 /32 address", quote(&peer.name))),
        };
        if !seen.insert(host_route.clone()) {
            return Err(errorf!("WireGuard peer {} duplicates address {}", quote(&peer.name), host_route));
        }
        let _ = writeln!(buf, "# Peer: {}", peer.name);
        buf.push_str("[Peer]\n");
        let _ = writeln!(buf, "PublicKey = {}", peer.public_key);
        if !peer.preshared_key.is_empty() {
            let _ = writeln!(buf, "PresharedKey = {}", peer.preshared_key);
        }
        let _ = writeln!(buf, "AllowedIPs = {}", host_route);
        if !peer.endpoint.is_empty() {
            let _ = writeln!(buf, "Endpoint = {}", peer.endpoint);
        }
        buf.push_str("PersistentKeepalive = 25\n\n");
    }
    Ok(buf)
}

/// Client configuration text and QR code payload.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ClientConfigBundle {
    pub config_text: String,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub qr_code_data: String,
}

/// A ready-to-import split-tunnel client configuration. Only explicitly
/// supplied private subnets are routed through the tunnel.
pub fn generate_client_config(
    client_private_key: &str,
    client_ip: &str,
    server_public_key: &str,
    server_endpoint: &str,
    preshared_key: &str,
    dns_servers: &str,
    routed_cidrs: &[String],
) -> Result<ClientConfigBundle> {
    let mut buf = String::new();
    buf.push_str("[Interface]\n");
    let _ = writeln!(buf, "PrivateKey = {}", client_private_key);
    let _ = writeln!(buf, "Address = {}", client_ip);
    if !dns_servers.is_empty() {
        let _ = writeln!(buf, "DNS = {}", dns_servers);
    }
    buf.push_str("\n[Peer]\n");
    let _ = writeln!(buf, "PublicKey = {}", server_public_key);
    if !preshared_key.is_empty() {
        let _ = writeln!(buf, "PresharedKey = {}", preshared_key);
    }
    if !server_endpoint.is_empty() {
        let _ = writeln!(buf, "Endpoint = {}", server_endpoint);
    }
    let mut allowed = Vec::new();
    let mut seen = HashSet::new();
    for raw in routed_cidrs {
        let normalized = match net::parse_cidr(raw.trim()) {
            Some((ip, n)) if ip.to4().is_some() => n.to_string(),
            _ => return Err(errorf!("invalid routed IPv4 CIDR {}", quote(raw))),
        };
        if seen.insert(normalized.clone()) {
            allowed.push(normalized);
        }
    }
    if allowed.is_empty() {
        // Compatibility fallback; never defaults to 0.0.0.0/0.
        match net::parse_cidr(client_ip) {
            Some((ip, n)) if ip.to4().is_some() => allowed.push(n.to_string()),
            _ => return Err(errorf!("client CIDR is invalid")),
        }
    }
    let _ = writeln!(buf, "AllowedIPs = {}", allowed.join(", "));
    buf.push_str("PersistentKeepalive = 25\n");
    let png = qr_png(&buf).map_err(|e| wrapf("encode WireGuard QR", e))?;
    Ok(ClientConfigBundle { config_text: buf, qr_code_data: format!("data:image/png;base64,{}", STANDARD.encode(png)) })
}

/// A medium error-correction QR code as a 1-bit PNG with an 8-pixel module
/// and a 4-module quiet zone, the same geometry rsc.io/qr renders.
fn qr_png(text: &str) -> Result<Vec<u8>> {
    let code = qrcode::QrCode::with_error_correction_level(text.as_bytes(), qrcode::EcLevel::M).map_err(|e| errorf!("{}", e))?;
    let width = code.width();
    let colors = code.to_colors();
    let scale = 8usize;
    let side = (width + 8) * scale;
    let row_bytes = side.div_ceil(8);
    let mut pixels = vec![0xffu8; row_bytes * side];
    for y in 0..width {
        for x in 0..width {
            if colors[y * width + x] != qrcode::Color::Dark {
                continue;
            }
            for dy in 0..scale {
                for dx in 0..scale {
                    let px = (x + 4) * scale + dx;
                    let py = (y + 4) * scale + dy;
                    pixels[py * row_bytes + px / 8] &= !(0x80 >> (px % 8));
                }
            }
        }
    }
    let mut out = Vec::new();
    {
        let mut encoder = png::Encoder::new(&mut out, side as u32, side as u32);
        encoder.set_color(png::ColorType::Grayscale);
        encoder.set_depth(png::BitDepth::One);
        let mut writer = encoder.write_header().map_err(|e| errorf!("{}", e))?;
        writer.write_image_data(&pixels).map_err(|e| errorf!("{}", e))?;
    }
    Ok(out)
}

/// An RFC 7748 X25519 keypair in WireGuard's base64 representation.
pub fn generate_wireguard_keypair() -> Result<(String, String)> {
    let mut private = crate::goish::rand::bytes(32).map_err(|e| wrapf("generate WireGuard private key", errorf!("{}", e)))?;
    private[0] &= 248;
    private[31] &= 127;
    private[31] |= 64;
    let public = x25519_base(&private);
    Ok((STANDARD.encode(&private), STANDARD.encode(public)))
}

fn x25519_base(private: &[u8]) -> [u8; 32] {
    let mut scalar = [0u8; 32];
    scalar.copy_from_slice(private);
    x25519_dalek::x25519(scalar, x25519_dalek::X25519_BASEPOINT_BYTES)
}

pub fn wireguard_public_key(private_key: &str) -> Result<String> {
    let private = STANDARD.decode(private_key).ok().filter(|p| p.len() == 32).ok_or_else(|| errorf!("invalid WireGuard private key"))?;
    let public = x25519_base(&private);
    // Go's curve25519.X25519 rejects a low-order result.
    if public.iter().all(|b| *b == 0) {
        return Err(errorf!("derive WireGuard public key: bad input point: low order point"));
    }
    Ok(STANDARD.encode(public))
}

pub fn generate_wireguard_preshared_key() -> Result<String> {
    let key = crate::goish::rand::bytes(32).map_err(|e| wrapf("generate WireGuard preshared key", errorf!("{}", e)))?;
    Ok(STANDARD.encode(key))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rfc7748_public_key_matches_known_vector() {
        // RFC 7748 section 6.1 Alice's key pair.
        let private = hex::decode("77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a").unwrap();
        let public = wireguard_public_key(&STANDARD.encode(private)).unwrap();
        assert_eq!(hex::encode(STANDARD.decode(public).unwrap()), "8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a");
    }

    #[test]
    fn client_config_has_qr_payload() {
        let (private, public) = generate_wireguard_keypair().unwrap();
        let bundle = generate_client_config(&private, "10.8.0.2/32", &public, "203.0.113.1:51820", "", "10.8.0.1", &["192.168.1.0/24".into()]).unwrap();
        assert!(bundle.config_text.contains("AllowedIPs = 192.168.1.0/24\n"));
        assert!(bundle.qr_code_data.starts_with("data:image/png;base64,iVBORw0KGgo"));
    }
}
