//! The narrow contract between routerd and router-applyd for opt-in DNS
//! lookup statistics. It lives outside apply/config/services so the bootstrap
//! tools stay unaffected; the helper is reached over a dedicated socket.

use serde::{Deserialize, Serialize};
use std::time::{Duration, Instant};

use crate::errorf;
use crate::goish::errors::Result;

/// The helper's DNS activity socket, next to apply.sock.
pub const SOCKET_PATH: &str = "/run/minimalrouter/dns-activity.sock";
/// On tmpfs, so query lines never reach the disk.
pub const QUERY_LOG_PATH: &str = "/run/minimalrouter-dns-queries.log";
/// Read by dnsmasq through conf-dir alongside the generated configuration.
pub const DROP_IN_PATH: &str = "/etc/dnsmasq.d/minimalrouter-dns-activity.conf";

pub const PROTOCOL_VERSION: i64 = 1;
pub const MAX_REQUEST_BYTES: usize = 4 << 10;
pub const MAX_RESPONSE_BYTES: usize = 256 << 10;

/// The only content the helper ever writes to DROP_IN_PATH. Asynchronous
/// logging drops lines instead of delaying answers.
pub fn drop_in() -> String {
    drop_in_for(QUERY_LOG_PATH)
}

pub fn drop_in_for(log_path: &str) -> String {
    format!(
        "# Generated by Minimal Router OS — DNS activity statistics\n# Queries are logged to tmpfs and drained by router-applyd every minute.\nlog-queries\nlog-facility={}\nlog-async=50\n",
        log_path
    )
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Request {
    pub version: i64,
    pub enabled: bool,
}

/// How often one client looked up one name since the previous drain.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct Lookup {
    pub client: String,
    pub name: String,
    pub count: u32,
    pub last_seen: i64,
}

/// One page of drained lookups.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Response {
    pub success: bool,
    #[serde(skip_serializing_if = "String::is_empty")]
    pub error: String,
    pub enabled: bool,
    pub entries: Vec<Lookup>,
    pub dropped: u64,
    pub more: bool,
}

pub struct Client {
    pub socket_path: String,
}

impl Default for Client {
    fn default() -> Self {
        Client { socket_path: SOCKET_PATH.into() }
    }
}

impl Client {
    #[cfg(unix)]
    pub fn drain(&self, deadline: Instant, enabled: bool) -> Result<Response> {
        use std::io::{Read, Write};
        use std::os::unix::net::UnixStream;
        let mut stream = UnixStream::connect(&self.socket_path).map_err(|e| errorf!("connect to router-applyd DNS activity socket: {}", e))?;
        let deadline = deadline.min(Instant::now() + Duration::from_secs(30));
        let remaining = deadline.saturating_duration_since(Instant::now()).max(Duration::from_millis(1));
        stream.set_read_timeout(Some(remaining))?;
        stream.set_write_timeout(Some(remaining))?;
        let mut body = crate::goish::json::marshal(&Request { version: PROTOCOL_VERSION, enabled })?;
        body.push(b'\n');
        stream.write_all(&body).map_err(|e| errorf!("send DNS activity request: {}", e))?;
        stream.shutdown(std::net::Shutdown::Write)?;
        let mut data = Vec::new();
        stream.take(MAX_RESPONSE_BYTES as u64 + 1).read_to_end(&mut data).map_err(|e| errorf!("read DNS activity response: {}", e))?;
        decode_response(&data)
    }

    #[cfg(not(unix))]
    pub fn drain(&self, _deadline: Instant, _enabled: bool) -> Result<Response> {
        let _ = Duration::ZERO;
        Err(errorf!("connect to router-applyd DNS activity socket: unix sockets are unavailable on this platform"))
    }
}

/// Exactly one bounded response object.
pub fn decode_response(data: &[u8]) -> Result<Response> {
    if data.len() > MAX_RESPONSE_BYTES {
        return Err(errorf!("DNS activity response exceeds limit"));
    }
    let mut response: Response = match crate::apply::decode_single(data) {
        Ok(r) => r,
        Err(crate::apply::SingleDecodeError::Trailing) => return Err(errorf!("DNS activity response has trailing data")),
        Err(crate::apply::SingleDecodeError::Invalid(e)) => return Err(errorf!("decode DNS activity response: {}", e)),
    };
    if !response.success {
        if response.error.is_empty() {
            response.error = "DNS activity request failed".into();
        }
        return Err(errorf!("{}", response.error));
    }
    Ok(response)
}

/// Exactly one bounded request object.
pub fn decode_request(data: &[u8]) -> Result<Request> {
    if data.len() > MAX_REQUEST_BYTES {
        return Err(errorf!("invalid or oversized DNS activity request"));
    }
    let request: Request = match crate::apply::decode_single(data) {
        Ok(r) => r,
        Err(crate::apply::SingleDecodeError::Trailing) => return Err(errorf!("DNS activity request must contain exactly one object")),
        Err(crate::apply::SingleDecodeError::Invalid(_)) => return Err(errorf!("invalid DNS activity request")),
    };
    if request.version != PROTOCOL_VERSION {
        return Err(errorf!("unsupported DNS activity protocol version"));
    }
    Ok(request)
}
