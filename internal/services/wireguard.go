package services

import (
	"bytes"
	"fmt"
	"net"
	"strings"

	"github.com/vladimirperovic/minimalrouter/internal/config"
)

type WireGuardConfig = config.WireGuardConfig
type WireGuardPeer = config.WireGuardPeer

// GenerateWireGuard renders the human-readable appliance configuration. It
// includes Address, which is applied by the privileged helper with a fixed
// ip(8) argv and is not valid input for wg setconf.
func GenerateWireGuard(wg *WireGuardConfig) (string, error) {
	return generateWireGuard(wg, true)
}

// GenerateWireGuardRuntime renders only directives accepted by wg setconf.
// Keeping the runtime file separate removes the need for wg-quick (and Bash)
// without parsing or executing shell hooks from configuration.
func GenerateWireGuardRuntime(wg *WireGuardConfig) (string, error) {
	return generateWireGuard(wg, false)
}

// GenerateWireGuardClientRuntime renders the outbound tunnel (wg1) runtime
// input. It mirrors the server-side format: an [Interface] with the private
// key followed by the single remote [Peer]. The interface address and routes
// are applied by the privileged helper.
func GenerateWireGuardClientRuntime(wg *config.WGClientConfig) (string, error) {
	// A route-only wg1 with no local address is not a supported appliance
	// topology. Enforce this in the generator as well as model validation so
	// the privileged helper remains fail-closed even if a compromised or buggy
	// control plane bypasses normal validation.
	clientIP, clientNet, err := net.ParseCIDR(strings.TrimSpace(wg.Address))
	if err != nil || clientIP.To4() == nil {
		return "", fmt.Errorf("WireGuard client address is required and must be a valid IPv4 /32")
	}
	if ones, bits := clientNet.Mask.Size(); bits != 32 || ones != 32 {
		return "", fmt.Errorf("WireGuard client address must be an IPv4 /32")
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by Minimal Router OS — do not edit manually\n")
	buf.WriteString("# Runtime input for wg setconf; interface address is applied separately\n\n")
	buf.WriteString("[Interface]\n")
	buf.WriteString(fmt.Sprintf("PrivateKey = %s\n", wg.PrivateKey))
	buf.WriteString("\n")

	if len(wg.AllowedIPs) == 0 {
		return "", fmt.Errorf("WireGuard client must list at least one allowed network")
	}
	seenNets := make(map[string]struct{})
	allowed := make([]string, 0, len(wg.AllowedIPs))
	for _, entry := range wg.AllowedIPs {
		_, network, err := net.ParseCIDR(strings.TrimSpace(entry))
		if err != nil || network.IP.To4() == nil {
			return "", fmt.Errorf("WireGuard client allowed network %q must be valid IPv4 CIDR", entry)
		}
		cidr := network.String()
		if _, dup := seenNets[cidr]; dup {
			return "", fmt.Errorf("WireGuard client duplicates allowed network %s", cidr)
		}
		seenNets[cidr] = struct{}{}
		allowed = append(allowed, cidr)
	}

	buf.WriteString("# Peer: remote site (outbound tunnel)\n")
	buf.WriteString("[Peer]\n")
	buf.WriteString(fmt.Sprintf("PublicKey = %s\n", wg.PublicKey))
	if wg.PresharedKey != "" {
		buf.WriteString(fmt.Sprintf("PresharedKey = %s\n", wg.PresharedKey))
	}
	buf.WriteString(fmt.Sprintf("AllowedIPs = %s\n", strings.Join(allowed, ", ")))
	if wg.Endpoint != "" {
		buf.WriteString(fmt.Sprintf("Endpoint = %s\n", wg.Endpoint))
	}
	// Validation allows 0..65535 and wg(8) treats 0 as "keepalive disabled",
	// so the configured value is emitted verbatim; an explicit zero must not
	// silently become a 25-second keepalive.
	buf.WriteString(fmt.Sprintf("PersistentKeepalive = %d\n", wg.PersistentKeepalive))
	return buf.String(), nil
}

func generateWireGuard(wg *WireGuardConfig, includeAddress bool) (string, error) {
	var buf bytes.Buffer
	seenPeerIPs := make(map[string]struct{})

	buf.WriteString("# Generated by Minimal Router OS — do not edit manually\n")
	if includeAddress {
		buf.WriteString("# Runtime file: /run/minimalrouter/wg0.conf\n\n")
	} else {
		buf.WriteString("# Runtime input for wg setconf; interface address is applied separately\n\n")
	}

	buf.WriteString("[Interface]\n")
	buf.WriteString(fmt.Sprintf("PrivateKey = %s\n", wg.PrivateKey))
	if wg.ListenPort > 0 {
		buf.WriteString(fmt.Sprintf("ListenPort = %d\n", wg.ListenPort))
	} else {
		buf.WriteString("ListenPort = 51820\n")
	}
	if includeAddress {
		buf.WriteString(fmt.Sprintf("Address = %s\n", wg.Address))
	}
	buf.WriteString("\n")

	for _, peer := range wg.Peers {
		if !peer.Enabled {
			continue
		}
		if len(peer.AllowedIPs) != 1 {
			return "", fmt.Errorf("WireGuard peer %q must have exactly one IPv4 /32 address", peer.Name)
		}
		ip, network, err := net.ParseCIDR(strings.TrimSpace(peer.AllowedIPs[0]))
		ones, bits := 0, 0
		if network != nil {
			ones, bits = network.Mask.Size()
		}
		if err != nil || ip.To4() == nil || bits != 32 || ones != 32 {
			return "", fmt.Errorf("WireGuard peer %q must use an IPv4 /32 address", peer.Name)
		}
		hostRoute := network.String()
		if _, exists := seenPeerIPs[hostRoute]; exists {
			return "", fmt.Errorf("WireGuard peer %q duplicates address %s", peer.Name, hostRoute)
		}
		seenPeerIPs[hostRoute] = struct{}{}

		buf.WriteString("# Peer: " + peer.Name + "\n")
		buf.WriteString("[Peer]\n")
		buf.WriteString(fmt.Sprintf("PublicKey = %s\n", peer.PublicKey))

		if peer.PresharedKey != "" {
			buf.WriteString(fmt.Sprintf("PresharedKey = %s\n", peer.PresharedKey))
		}

		buf.WriteString(fmt.Sprintf("AllowedIPs = %s\n", hostRoute))

		if peer.Endpoint != "" {
			buf.WriteString(fmt.Sprintf("Endpoint = %s\n", peer.Endpoint))
		}
		buf.WriteString("PersistentKeepalive = 25\n\n")
	}

	return buf.String(), nil
}
