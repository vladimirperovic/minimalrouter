package services

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/vladimirperovic/minimalrouter/internal/config"
)

// GenerateDnsmasq renders dnsmasq DHCP & DNS server configuration.
func GenerateDnsmasq(cfg *config.SystemConfig) (string, error) {
	var buf bytes.Buffer

	buf.WriteString("# Generated by Minimal Router OS — do not edit manually\n")
	buf.WriteString("# File: /etc/dnsmasq.d/minimalrouter.conf\n\n")

	// Domain & Interface binding
	buf.WriteString(fmt.Sprintf("domain=%s\n", cfg.System.Domain))
	buf.WriteString(fmt.Sprintf("interface=%s\n", cfg.LAN.Interface))
	buf.WriteString("bind-interfaces\n")
	buf.WriteString("bogus-priv\n")
	buf.WriteString("domain-needed\n\n")

	// Upstream DNS Servers
	if len(cfg.DHCP.DNSServers) > 0 {
		buf.WriteString("# Upstream DNS Servers\n")
		for _, dns := range cfg.DHCP.DNSServers {
			buf.WriteString(fmt.Sprintf("server=%s\n", dns))
		}
		buf.WriteString("\n")
	}

	// DHCP Server settings
	if cfg.DHCP.Enabled {
		buf.WriteString("# DHCP Pool\n")
		buf.WriteString(fmt.Sprintf("dhcp-range=%s,%s,%s,%s\n\n",
			cfg.LAN.Interface,
			cfg.DHCP.RangeStart,
			cfg.DHCP.RangeEnd,
			cfg.DHCP.LeaseTime,
		))

		// Static Leases
		if len(cfg.DHCP.StaticLeases) > 0 {
			buf.WriteString("# Static DHCP Leases\n")
			for _, lease := range cfg.DHCP.StaticLeases {
				hostname := strings.TrimSpace(lease.Hostname)
				if hostname != "" {
					buf.WriteString(fmt.Sprintf("dhcp-host=%s,%s,%s\n", lease.MAC, lease.IPAddress, hostname))
				} else {
					buf.WriteString(fmt.Sprintf("dhcp-host=%s,%s\n", lease.MAC, lease.IPAddress))
				}
			}
		}
	} else {
		buf.WriteString("# DHCP Disabled\n")
	}

	return buf.String(), nil
}
