package services

import (
	"bytes"
	"fmt"

	"github.com/vladimirperovic/minimalrouter/internal/config"
)

// GenerateCloudflareDDNS produces a script that updates a Cloudflare DNS A record
// to point to the router's current public IP. This runs periodically via cron.
func GenerateCloudflareDDNS(cfg *config.SystemConfig) (string, error) {
	if !cfg.Cloudflare.DDNSEnabled || cfg.Cloudflare.APIToken == "" || cfg.Cloudflare.Domain == "" {
		return "# Cloudflare DDNS disabled or not configured\n", nil
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by Minimal Router OS — Cloudflare Dynamic DNS updater\n")
	buf.WriteString("# Runs every 5 minutes via cron to keep DNS record current\n\n")

	token := cfg.Cloudflare.APIToken
	zoneID := cfg.Cloudflare.ZoneID
	domain := cfg.Cloudflare.Domain

	// Generate inadyn-compatible config for Cloudflare DDNS
	buf.WriteString("# inadyn Cloudflare DDNS configuration\n")
	buf.WriteString("# File: /etc/inadyn.conf\n\n")
	buf.WriteString(fmt.Sprintf("provider cloudflare.com {\n"))
	buf.WriteString(fmt.Sprintf("    username = %s\n", zoneID))
	buf.WriteString(fmt.Sprintf("    password = %s\n", token))
	buf.WriteString(fmt.Sprintf("    hostname = %s\n", domain))
	buf.WriteString(fmt.Sprintf("    ttl = 300\n"))
	buf.WriteString("}\n\n")

	// Also generate a manual update script as fallback
	buf.WriteString("# Manual update script (fallback)\n")
	buf.WriteString("#!/bin/sh\n")
	buf.WriteString(fmt.Sprintf("ZONE_ID=\"%s\"\n", zoneID))
	buf.WriteString(fmt.Sprintf("API_TOKEN=\"%s\"\n", token))
	buf.WriteString(fmt.Sprintf("DOMAIN=\"%s\"\n", domain))
	buf.WriteString("RECORD_TYPE=\"A\"\n")
	buf.WriteString("TTL=300\n\n")
	buf.WriteString("CURRENT_IP=$(curl -s https://api.ipify.org)\n")
	buf.WriteString("if [ -z \"$CURRENT_IP\" ]; then\n")
	buf.WriteString("    echo \"Failed to detect public IP\"\n")
	buf.WriteString("    exit 1\n")
	buf.WriteString("fi\n\n")
	buf.WriteString("RECORD_ID=$(curl -s -X GET \\\n")
	buf.WriteString("    \"https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?type=A&name=$DOMAIN\" \\\n")
	buf.WriteString("    -H \"Authorization: Bearer $API_TOKEN\" \\\n")
	buf.WriteString("    -H \"Content-Type: application/json\" | grep -o '\"id\":\"[^\"]*\"' | head -1 | cut -d'\"' -f4)\n\n")
	buf.WriteString("if [ -z \"$RECORD_ID\" ]; then\n")
	buf.WriteString("    echo \"DNS record not found, creating...\"\n")
	buf.WriteString("    curl -s -X POST \\\n")
	buf.WriteString("        \"https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records\" \\\n")
	buf.WriteString("        -H \"Authorization: Bearer $API_TOKEN\" \\\n")
	buf.WriteString("        -H \"Content-Type: application/json\" \\\n")
	buf.WriteString("        --data '{\"type\":\"A\",\"name\":\"$DOMAIN\",\"content\":\"'$CURRENT_IP'\",\"ttl\":'$TTL',\"proxied\":false}'\n")
	buf.WriteString("else\n")
	buf.WriteString("    echo \"Updating DNS record $RECORD_ID to $CURRENT_IP\"\n")
	buf.WriteString("    curl -s -X PUT \\\n")
	buf.WriteString("        \"https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records/$RECORD_ID\" \\\n")
	buf.WriteString("        -H \"Authorization: Bearer $API_TOKEN\" \\\n")
	buf.WriteString("        -H \"Content-Type: application/json\" \\\n")
	buf.WriteString("        --data '{\"type\":\"A\",\"name\":\"$DOMAIN\",\"content\":\"'$CURRENT_IP'\",\"ttl\":'$TTL',\"proxied\":false}'\n")
	buf.WriteString("fi\n")

	return buf.String(), nil
}

// GenerateCloudflareTunnel produces a cloudflared tunnel configuration file.
// The actual tunnel token must be obtained from the Cloudflare dashboard.
func GenerateCloudflareTunnel(cfg *config.SystemConfig) (string, error) {
	if !cfg.Cloudflare.TunnelEnabled || cfg.Cloudflare.TunnelToken == "" {
		return "# Cloudflare Tunnel disabled or not configured\n", nil
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by Minimal Router OS — Cloudflare Tunnel (cloudflared)\n")
	buf.WriteString("# File: /etc/cloudflared/config.yml\n\n")

	token := cfg.Cloudflare.TunnelToken

	buf.WriteString("tunnel: minimalrouter\n")
	buf.WriteString("credentials-file: /etc/cloudflared/credentials.json\n\n")
	buf.WriteString("ingress:\n")
	buf.WriteString("  - hostname: " + cfg.Cloudflare.Domain + "\n")
	buf.WriteString("    service: https://localhost:" + fmt.Sprintf("%d", cfg.System.HTTPSPort) + "\n")
	buf.WriteString("    originRequest:\n")
	buf.WriteString("      noTLSVerify: false\n")
	buf.WriteString("  - service: http_status:404\n\n")

	buf.WriteString("# Tunnel token (for systemd service)\n")
	buf.WriteString("# cloudflared service install " + token + "\n")

	return buf.String(), nil
}
